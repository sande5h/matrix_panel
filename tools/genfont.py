FIRST, LAST = 0x20, 0x5A          # space .. Z

def columns(art):
    rows = art.split()
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), art
    # one byte per column, bit n = row n
    return [sum((1 << y) for y in range(7) if rows[y][x] == '#') for x in range(5)]

out = []
out.append("""#pragma once

#include <stdint.h>

/* A 5x7 bitmap font, one byte per column, bit n is row n (top down). Covers
 * 0x20..0x5A -- space, digits, the punctuation a clock needs, and A..Z.
 * Anything outside that range renders blank. Generated from the glyph art in
 * tools/genfont.py; edit there, not here. */

#define FONT5X7_FIRST 0x%02X
#define FONT5X7_LAST  0x%02X
#define FONT5X7_W     5
#define FONT5X7_H     7

static const uint8_t font5x7[FONT5X7_LAST - FONT5X7_FIRST + 1][FONT5X7_W] = {""" % (FIRST, LAST))

for code in range(FIRST, LAST + 1):
    ch = chr(code)
    cols = columns(G[ch]) if ch in G else [0] * 5
    name = "space" if ch == ' ' else ch
    out.append("    { %s },   /* %s */" % (", ".join("0x%02X" % c for c in cols), name))

out.append("};")
print("\n".join(out))
